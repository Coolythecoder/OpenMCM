set_xmakever("3.1.1")
local commonlib = os.getenv("OPENMCM_COMMONLIBSSE_NG")
local version = os.getenv("OPENMCM_BROWSER_VERSION")
local major, minor, patch = version:match("^(%d+)%.(%d+)%.(%d+)")
set_config("skyrim_se", true)
set_config("skyrim_ae", true)
set_config("skyrim_vr", false)
includes(path.join(commonlib, "xmake.lua"))
set_project("OpenMCMBrowser")
set_languages("c++23")
set_arch("x64")
set_encodings("utf-8")
add_rules("mode.debug", "mode.release")
target("OpenMCMBrowser")
    set_kind("shared")
    add_deps("commonlibsse-ng")
    add_files("Bridge.cpp", "ProfileStore.cpp", "ProfileCodec.cpp")
    add_includedirs(".")
    add_defines('OPENMCM_BROWSER_VERSION="' .. version .. '"')
    add_defines("OPENMCM_BROWSER_MAJOR=" .. major, "OPENMCM_BROWSER_MINOR=" .. minor, "OPENMCM_BROWSER_PATCH=" .. patch)
    add_shflags("/Brepro", { force = true })
target("BrowserNativeTests")
    set_kind("binary")
    set_default(false)
    add_files("ProfileStore.cpp", "ProfileCodec.cpp", "tests/ProfileStoreTests.cpp")
    add_includedirs(".")
target("ProfileCodecTests")
    set_kind("binary")
    set_default(false)
    add_files("ProfileCodec.cpp", "tests/ProfileCodecTests.cpp")
    add_includedirs(".")
